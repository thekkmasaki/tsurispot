import type { CatchableFish, FishingSpot, FishSpecies, Region } from "@/types";
import { getFishBySlug } from "./fish";

function fish(slug: string): FishSpecies {
  const f = getFishBySlug(slug);
  if (!f) throw new Error(`Fish not found: ${slug}`);
  return f;
}

function cf(
  slug: string,
  monthStart: number,
  monthEnd: number,
  peakSeason: boolean,
  catchDifficulty: CatchableFish["catchDifficulty"],
  recommendedTime: string,
  method: string,
  source: string,
): CatchableFish {
  return { fish: fish(slug), monthStart, monthEnd, peakSeason, catchDifficulty, recommendedTime, method, source };
}

